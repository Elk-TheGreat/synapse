"""Python source generation.

What this produces is a real, self-contained Python program: it can be run with
``python program.py`` and it executes the same program the editor runs.  The
generated module embeds the compiled graph and drives it through the SYNAPSE
engine, which keeps the output correct for every node type - including ones
whose logic cannot be expressed in a small amount of plain Python (scripts,
processes, network calls, functions).

The IR records which nodes have a native ``codegen`` lowering ("python" or
"unsupported").  Nodes marked unsupported are listed in the generated header so
the limitation is visible instead of hidden; lowering the whole graph to plain
Python without the engine is a separate, documented milestone.
"""

from __future__ import annotations

import datetime
import json
from typing import Any

from ..functions.library import FunctionDef
from ..graph.model import Graph
from .ir import CompiledGraph, build_ir

PROGRAM_TEMPLATE = '''#!/usr/bin/env python3
"""Generated by SYNAPSE from graph @@GRAPH_NAME@@ on @@DATE@@.

Run:  python @@MODULE@@.py [--set input=value ...] [--pretty]
Exit code 0 means every node succeeded.

Generated nodes without a native Python lowering (@@UNSUPPORTED_COUNT@@):
@@UNSUPPORTED_LIST@@
They run through the SYNAPSE engine embedded below, so behaviour is identical to
the editor.  Native translation of those constructs is not claimed.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys

GRAPH_JSON = json.loads(@@GRAPH@@)
FUNCTIONS_JSON = json.loads(@@FUNCTIONS@@)


def _boot():
    from synapse.graph.model import Graph
    from synapse.functions.library import FunctionDef, FunctionLibrary
    from synapse.nodes.registry import create_registry

    registry = create_registry()
    library = FunctionLibrary(registry)
    for data in FUNCTIONS_JSON:
        library.add(FunctionDef.from_dict(data, registry=registry))
    graph = Graph.from_dict(GRAPH_JSON, registry=registry)
    return graph, registry, library


def _coerce(text: str):
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        return text


async def _run(inputs: dict, pretty: bool) -> int:
    from synapse.engine.executor import ExecutionOptions, Executor

    graph, registry, library = _boot()
    executor = Executor(registry, library)
    result = await executor.run(graph, inputs=inputs, options=ExecutionOptions())
    for err in result.errors:
        print(f"error in {err.node_name}: {err}", file=sys.stderr)
    payload = {
        "status": result.status,
        "outputs": result.outputs,
        "duration": result.duration,
        "nodes": {node_id: node.to_dict() for node_id, node in result.nodes.items()},
        "errors": [str(err) for err in result.errors],
    }
    print(json.dumps(payload, indent=2 if pretty else None, default=str))
    return 0 if result.ok else 1


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Run the exported SYNAPSE graph")
    parser.add_argument("--set", action="append", default=[], metavar="NAME=VALUE",
                        help="graph input value (JSON when it parses, else a string)")
    parser.add_argument("--pretty", action="store_true", help="indent the JSON result")
    args = parser.parse_args(argv)
    inputs = {}
    for item in args.set:
        if "=" not in item:
            parser.error(f"--set expects NAME=VALUE, got {item!r}")
        name, _, value = item.partition("=")
        inputs[name] = _coerce(value)
    return asyncio.run(_run(inputs, args.pretty))


if __name__ == "__main__":
    raise SystemExit(main())
'''


def _python_literal(payload: Any) -> str:
    return json.dumps(json.dumps(payload, ensure_ascii=False))


def generate_python(
    graph: Graph,
    *,
    functions=None,
    module_name: str = "synapse_program",
    date: str | None = None,
    pretty: bool = True,
    compiled: CompiledGraph | None = None,
) -> str:
    """Return Python source for ``graph`` (and the functions it calls)."""
    compiled = compiled or build_ir(graph, functions=functions)
    function_defs: list[dict] = []
    if functions is not None:
        for function in functions:
            if function.id in compiled.functions:
                function_defs.append(function.to_dict())
    unsupported = sorted({n.definition.name for n in compiled.unsupported_nodes()})
    return (
        PROGRAM_TEMPLATE.replace("@@GRAPH_NAME@@", repr(compiled.name))
        .replace("@@MODULE@@", module_name)
        .replace("@@DATE@@", date or datetime.date.today().isoformat())
        .replace("@@GRAPH@@", _python_literal(graph.to_dict()))
        .replace("@@FUNCTIONS@@", _python_literal(function_defs))
        .replace("@@UNSUPPORTED_COUNT@@", str(len(compiled.unsupported_nodes())))
        .replace("@@UNSUPPORTED_LIST@@", ", ".join(unsupported) if unsupported else "none")
    )


def generate_json(graph: Graph, *, functions=None, compiled: CompiledGraph | None = None) -> dict:
    """Portable JSON export: graph, referenced functions and IR statistics."""
    compiled = compiled or build_ir(graph, functions=functions)
    used = set(compiled.functions)
    return {
        "format": "synapse.graph",
        "format_version": 1,
        "graph": graph.to_dict(),
        "functions": [
            f.to_dict() for f in (functions or []) if f.id in used
        ],
        "compiled": {
            "order": compiled.order,
            "nodes": [
                {
                    "id": node.id,
                    "type": node.type_id,
                    "inputs": {
                        name: {
                            "source": spec.source_node,
                            "port": spec.source_port,
                            "literal": spec.literal if isinstance(spec.literal, (str, int, float, bool, type(None))) else repr(spec.literal),
                        }
                        for name, spec in node.inputs.items()
                    },
                    "codegen": node.codegen,
                }
                for node in compiled.nodes
            ],
            "warnings": compiled.warnings,
        },
    }


__all__ = ["generate_python", "generate_json", "PROGRAM_TEMPLATE"]
