import json
import os
import subprocess
import sys
from pathlib import Path

from conftest import build_sum_graph
from synapse.compiler import build_ir, generate_json, generate_python
from synapse.graph.model import Graph


def test_ir_resolves_inputs(registry):
    g = build_sum_graph(registry, 3, 4)
    compiled = build_ir(g)
    assert compiled.name == g.name
    assert len(compiled.nodes) == len(g.nodes)
    add_node = next(n for n in compiled.nodes if n.type_id == "math.add")
    assert set(add_node.inputs) == {"a", "b"}
    assert add_node.inputs["a"].source_node
    assert compiled.unsupported_nodes() == [] or all(
        n.type_id == "core.graph_output" for n in compiled.unsupported_nodes()
    )


def test_codegen_python_program_runs(registry, tmp_path):
    g = build_sum_graph(registry, 17, 25)
    source = generate_python(g, module_name="exported_demo")
    assert "exported_demo" in source
    assert "Generated by SYNAPSE from graph 'Sum'" in source
    script = tmp_path / "program.py"
    script.write_text(source, encoding="utf-8")
    env = {**os.environ, "PYTHONPATH": str(Path.cwd())}
    proc = subprocess.run([sys.executable, str(script)], capture_output=True, text=True, env=env, timeout=60)
    assert proc.returncode == 0, proc.stderr
    payload = json.loads(proc.stdout)
    assert payload["status"] == "ok"
    assert payload["outputs"] == {"sum": 42}


def test_json_export_is_loadable(registry):
    g = build_sum_graph(registry, 1, 1)
    payload = generate_json(g)
    assert payload["format"] == "synapse.graph" and payload["format_version"] == 1
    restored = Graph.from_dict(payload["graph"], registry=registry)
    assert set(restored.nodes) == set(g.nodes)
    assert len(restored.edges) == len(g.edges)


def test_python_source_quotes_hostile_strings(registry):
    g = Graph("g", "Quote", registry=registry)
    value = g.add_node("core.constant", {"value_type": "string", "value": "it's \"quoted\"\nline"})
    out = g.add_node("core.graph_output", {"name": "text"})
    g.connect(value.id, "value", out.id, "value")
    source = generate_python(g)
    compile(source, "generated.py", "exec")
